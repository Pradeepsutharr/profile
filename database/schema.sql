CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS admin_accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), email text NOT NULL UNIQUE, password_hash text NOT NULL,
  is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS profile (
  id text PRIMARY KEY DEFAULT 'primary', name text NOT NULL, title text NOT NULL, intro text, summary text,
  email text, phone text, location text, avatar_url text, socials jsonb NOT NULL DEFAULT '{}'::jsonb,
  availability text, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS site_settings (
  id text PRIMARY KEY DEFAULT 'primary', colors jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS projects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), title text NOT NULL, slug text NOT NULL UNIQUE, excerpt text, description text,
  image_url text, gallery jsonb NOT NULL DEFAULT '[]'::jsonb, tags text[] NOT NULL DEFAULT '{}', tech_stack text[] NOT NULL DEFAULT '{}',
  category text, client text, role text, year text, metrics jsonb NOT NULL DEFAULT '[]'::jsonb, challenge text, approach text, outcome text,
  project_url text, sort_order integer NOT NULL DEFAULT 0, published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS blog_posts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), title text NOT NULL, slug text NOT NULL UNIQUE, excerpt text, content text NOT NULL DEFAULT '',
  image_url text, category text, keywords text, published boolean NOT NULL DEFAULT false, published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), title text NOT NULL, slug text NOT NULL UNIQUE, description text, icon text,
  tags text[] NOT NULL DEFAULT '{}', sort_order integer NOT NULL DEFAULT 0, published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS skills (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name text NOT NULL, category text, score smallint NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
  sort_order integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS experience (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), company text NOT NULL, title text, start_date date, end_date date, location text, summary text,
  bullets text[] NOT NULL DEFAULT '{}', sort_order integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS education (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), institution text NOT NULL, degree text, start_date date, end_date date, location text, summary text,
  sort_order integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, email text NOT NULL, phone text, topic text, message text NOT NULL,
  attachment_url text, attachment_name text, status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'read', 'replied', 'archived')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS emails (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), gmail_message_id text UNIQUE, gmail_thread_id text, direction text CHECK (direction IN ('inbound', 'outbound')),
  from_email text, from_name text, to_email text, subject text, snippet text, body_html text, body_text text,
  is_read boolean NOT NULL DEFAULT false, is_starred boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

-- Keeps an immutable copy of every legacy content record during the one-time
-- migration. It is server-only and is never returned by public APIs.
CREATE TABLE IF NOT EXISTS legacy_source_records (
  source_table text NOT NULL,
  source_id text NOT NULL,
  payload jsonb NOT NULL,
  imported_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source_table, source_id)
);

CREATE INDEX IF NOT EXISTS projects_public_idx ON projects (published, sort_order, created_at DESC);
CREATE INDEX IF NOT EXISTS posts_public_idx ON blog_posts (published, published_at DESC);
CREATE INDEX IF NOT EXISTS services_public_idx ON services (published, sort_order);
CREATE INDEX IF NOT EXISTS contacts_created_idx ON contacts (created_at DESC);
CREATE INDEX IF NOT EXISTS emails_thread_idx ON emails (gmail_thread_id, created_at);

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;
DO $$ DECLARE table_name text; BEGIN
  FOREACH table_name IN ARRAY ARRAY['admin_accounts', 'profile', 'site_settings', 'projects', 'blog_posts', 'services', 'skills', 'experience', 'education', 'emails']
  LOOP EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', table_name || '_updated_at', table_name);
       EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', table_name || '_updated_at', table_name);
  END LOOP;
END $$;
